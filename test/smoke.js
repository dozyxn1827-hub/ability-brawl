const { chromium } = require('playwright');
(async () => {
  const browser = await chromium.launch({ executablePath: '/usr/bin/google-chrome', args: ['--no-sandbox', '--autoplay-policy=no-user-gesture-required'] });
  const ctx = await browser.newContext({ viewport: { width: 390, height: 780 }, deviceScaleFactor: 2, hasTouch: true, isMobile: true });
  const page = await ctx.newPage();
  const errs = [];
  page.on('pageerror', (e) => errs.push('PAGEERR ' + e.message + '\n' + (e.stack || '').split('\n').slice(0, 4).join('\n')));
  page.on('console', (m) => { if (m.type() === 'error') errs.push('CONSOLE ' + m.text()); });
  await page.goto('file://' + __dirname + '/../dist/index.html');
  await page.waitForTimeout(2500);
  await page.screenshot({ path: __dirname + '/s1-home.png' });
  await page.fill('#nick', '번개손');
  await page.click('text=한 기기에서 하기');
  await page.waitForTimeout(300);
  await page.screenshot({ path: __dirname + '/s2-setup.png' });
  await page.click('text=능력 쓰러 가기');
  await page.waitForTimeout(200);
  console.log('ability btn disabled when empty?', await page.isDisabled('button:has-text("이 능력으로 정하기")'), 'chips:', await page.locator('.chip').count());
  await page.fill('#ab-text', '아무 데서나 잠들 수 있다');
  await page.screenshot({ path: __dirname + '/s3-write.png' });
  await page.click('text=이 능력으로 정하기');
  await page.waitForTimeout(200);
  await page.fill('#sd-1', '쓸 때마다 "에취" 하고 재채기를 한다');
  await page.screenshot({ path: __dirname + '/s4-side.png', fullPage: true });
  console.log('side btn disabled before typing?', await page.isDisabled('button:has-text("부작용 확정")'));
  await page.click('text=부작용 확정');
  await page.waitForTimeout(600);
  await page.screenshot({ path: __dirname + '/s5-reveal.png', fullPage: true });
  await page.evaluate(() => { window.__snd = {}; const o = Sfx.play.bind(Sfx); Sfx.play = (n, st, ex) => { const k = n === 'move' && ex ? 'move:' + ((ex.mv.sfx && ex.mv.sfx.kind) || ex.mv.vfx) : n; window.__snd[k] = (window.__snd[k] || 0) + 1; return o(n, st, ex); }; });
  await page.waitForSelector('.ss', { timeout: 5000 }).catch(() => {}); await page.click('text=쇼 건너뛰기').catch(() => {}); await page.waitForTimeout(700);
  await page.click('text=바로 전투');
  await page.waitForTimeout(4500);
  await page.screenshot({ path: __dirname + '/s6-battle.png' });
  // 눌러 보기
  const tap = async (k, ms) => { const b = await page.$(`.pb[data-k="${k}"]`); const box = await b.boundingBox(); await page.mouse.move(box.x + box.width / 2, box.y + box.height / 2); await page.mouse.down(); await page.waitForTimeout(ms); await page.mouse.up(); };
  const joy = await (await page.$('.joy')).boundingBox();
  await page.mouse.move(joy.x + joy.width / 2, joy.y + joy.height / 2); await page.mouse.down();
  await page.mouse.move(joy.x + joy.width, joy.y + joy.height * 0.2, { steps: 4 }); await page.waitForTimeout(700); await page.mouse.up();
  await tap('a', 300); await tap('b', 100); await tap('c', 100); await tap('u', 100);
  await page.waitForTimeout(600);
  await page.waitForTimeout(3000);
  await page.screenshot({ path: __dirname + '/s7-battle2.png' });
  console.log('audio', JSON.stringify(await page.evaluate(() => ({ state: Sfx.ctx && Sfx.ctx.state, music: Music.cur, snd: window.__snd, bursts: App.root.querySelector('.battle') ? 'battle' : 'none' }))));
  const info = await page.evaluate(() => { const el = document.querySelector('.stage'); const r = el.getBoundingClientRect(); return { w: r.width, h: r.height, vw: innerWidth, vh: innerHeight, sw: document.documentElement.scrollWidth }; });
  console.log('stage', JSON.stringify(info));
  console.log(errs.length ? errs.join('\n') : 'no errors');
  await browser.close();
})();
